export function getAllAgents(): Agent[] {
  return [
    ...brandAgents,
    ...contentAgents,
    ...planningAgents,
    ...marketingAgents,
    ...advisorAgents,
  ];
}

export function getAgentsByCluster(cluster: string): Agent[] {
  return getAllAgents().filter(a => a.cluster === cluster);
}

export function getAgentById(id: string): Agent | undefined {
  return getAllAgents().find(a => a.id === id);
}

export function findBestAgentForInput(userInput: string): Agent {
  const lower = userInput.toLowerCase();
  const agents = getAllAgents();
  const scored = agents.map(agent => ({
    agent,
    score: agent.keywords.reduce(
      (acc, kw) => acc + (lower.includes(kw.toLowerCase()) ? 1 : 0),
      0
    ),
  }));
  scored.sort((a, b) => b.score - a.score);
  if (scored[0].score > 0) return scored[0].agent;
  return agents.find(a => a.id === 'advisor')!;
}

