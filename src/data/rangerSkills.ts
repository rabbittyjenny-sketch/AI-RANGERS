/** skill สูงสุดกี่ชิ้นต่อข้อความ — คุม token */
export const MAX_SKILLS_PER_MESSAGE = 2;

const esc = (t: string) => t.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** คำกระตุ้นภาษาอังกฤษ/ตัวเลขต้องเป็นคำเต็ม (กัน "usp" ไปติดใน "suspect") ส่วนคำไทยตรวจแบบมีอยู่ในข้อความ */
function hasTrigger(text: string, trigger: string): boolean {
  const t = trigger.toLowerCase();
  if (/[^\x00-\x7f]/.test(t)) return text.includes(t);
  return new RegExp(`(^|[^a-z0-9])${esc(t)}($|[^a-z0-9])`).test(text);
}

/** skill ของน้องนี้ที่ตรงกับข้อความผู้ใช้ เรียงตามจำนวนคำกระตุ้นที่เจอ (เท่ากัน = ลำดับในตาราง) */
export function selectSkills(agentId: string, userText: string, max = MAX_SKILLS_PER_MESSAGE): Skill[] {
  const text = (userText || '').toLowerCase();
  if (!text.trim()) return [];
  return RANGER_SKILLS
    .map((skill, order) => ({
      skill,
      order,
      score: skill.agent === agentId ? skill.triggers.filter(t => hasTrigger(text, t)).length : 0,
    }))
    .filter(x => x.score > 0)
    .sort((a, b) => b.score - a.score || a.order - b.order)
    .slice(0, max)
    .map(x => x.skill);
}

const SKILL_PREFACE = `ความรู้ประกอบสำหรับคำถามนี้ (ใช้เฉพาะส่วนที่ตรงกับสิ่งที่ผู้ใช้ถาม สรุปเป็นคำตอบสั้นตามรูปแบบของคุณ ห้ามคัดลอกทั้งหมด):
- ตัวเลขที่ใช้ต้องบอกแหล่งและปีตามที่ระบุ ข้อมูลต่างประเทศให้บอกว่าเป็นข้อมูลต่างประเทศ
- ห้ามเดาหรือเพิ่มตัวเลขที่ไม่อยู่ในนี้ ถ้าไม่พอให้บอกตรงๆ หรือค้นเว็บพร้อมที่มา
- เรื่องกฎหมายโฆษณา อาหาร เครื่องสำอาง อาหารเสริม ให้หลักการทั่วไปและแนะนำตรวจกับ สคบ./อย.`;

/** ข้อความผู้ใช้ + skill ที่เกี่ยวข้อง (ไม่ตรงเลย = คืนข้อความเดิมทุกตัวอักษร) */
export function withSkills(agentId: string, userText: string): string {
  const skills = selectSkills(agentId, userText);
  if (skills.length === 0) return userText;
  const blocks = skills.map(s => `### ${s.title}\n${s.body}`).join('\n\n');
  return `${userText}\n\n---\n${SKILL_PREFACE}\n\n${blocks}`;
}
